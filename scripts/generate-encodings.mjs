#!/usr/bin/env node
// Generates crates/pdf-render/src/text/encodings.rs: the simple-font
// encodings of ISO 32000-2, annex D, the Adobe Glyph List, the ZapfDingbats
// glyph list, and the widths of Symbol and ZapfDingbats.
//
//   node scripts/generate-encodings.mjs <encodings.js> <glyphlist.txt> \
//     <zapfdingbats.txt> <metrics.js>
//
// Sources (not fetched by this script, not committed):
// - pdf.js src/core/encodings.js and src/core/metrics.js (Apache-2.0),
//   commit 81525fd446779f0a29003cf06e3ba33751954826; the widths are those
//   of Adobe's Core 14 AFM files;
// - adobe-type-tools/agl-aglfn glyphlist.txt and zapfdingbats.txt
//   (BSD-3-Clause), commit 0276763a3cdf204a1badc283d90f5bc7ac13130d.
// The output is deterministic and checked by tests in pdf-render.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [encodingsPath, glyphlistPath, zapfPath, metricsPath] = process.argv.slice(2);
if (!encodingsPath || !glyphlistPath || !zapfPath || !metricsPath) {
  console.error(
    'usage: generate-encodings.mjs <encodings.js> <glyphlist.txt> <zapfdingbats.txt> <metrics.js>',
  );
  process.exit(2);
}
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'crates', 'pdf-render', 'src', 'text', 'encodings.rs');

const js = readFileSync(encodingsPath, 'utf8');
const tables = [
  ['STANDARD', 'StandardEncoding', 'StandardEncoding (D.2)'],
  ['WIN_ANSI', 'WinAnsiEncoding', 'WinAnsiEncoding (D.2)'],
  ['MAC_ROMAN', 'MacRomanEncoding', 'MacRomanEncoding (D.2)'],
  ['MAC_EXPERT', 'MacExpertEncoding', 'MacExpertEncoding (D.4)'],
  ['SYMBOL', 'SymbolSetEncoding', 'built-in encoding of Symbol (D.5)'],
  ['ZAPF_DINGBATS', 'ZapfDingbatsEncoding', 'built-in encoding of ZapfDingbats (D.6)'],
];
let rust = `//! Generated by \`scripts/generate-encodings.mjs\`; do not edit.
//!
//! Simple-font encodings (ISO 32000-2, annex D) and the widths of Symbol and
//! ZapfDingbats, from pdf.js \`src/core/encodings.js\` and
//! \`src/core/metrics.js\` (Apache-2.0, commit 81525fd4); the Adobe Glyph List
//! and the ZapfDingbats glyph list (BSD-3-Clause, Copyright 2002-2019 Adobe,
//! commit 0276763a). An empty name means no glyph for that code.

`;
for (const [rustName, jsName, doc] of tables) {
  const match = new RegExp(`const ${jsName} = \\[([\\s\\S]*?)\\];`).exec(js);
  if (!match) throw new Error(`${jsName} not found`);
  const names = JSON.parse(`[${match[1].replace(/,\s*$/, '')}]`);
  if (names.length !== 256) throw new Error(`${jsName}: ${names.length} entries`);
  if (names.some(n => typeof n !== 'string' || !/^[A-Za-z0-9._]*$/.test(n))) {
    throw new Error(`${jsName}: unexpected name`);
  }
  rust += `/// The ${doc}.\npub(crate) static ${rustName}: [&str; 256] = [\n`;
  for (let i = 0; i < 256; i += 8) {
    rust += `    ${names.slice(i, i + 8).map(n => JSON.stringify(n)).join(', ')},\n`;
  }
  rust += '];\n\n';
}

const byName = (a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0);
const unique = (entries, what) => {
  for (let i = 1; i < entries.length; i += 1) {
    if (entries[i][0] === entries[i - 1][0]) throw new Error(`${what}: duplicate ${entries[i][0]}`);
  }
};

// A glyph list: name -> first code point (a few names map to sequences;
// only the first is kept), sorted by name for binary search.
const glyphList = (file, rustName, doc) => {
  const entries = readFileSync(file, 'utf8')
    .split('\n')
    .filter(line => line && !line.startsWith('#'))
    .map(line => {
      const [name, codes] = line.trim().split(';');
      return [name, parseInt(codes.split(' ')[0], 16)];
    });
  entries.sort(byName);
  unique(entries, rustName);
  rust += `/// ${doc}, sorted by name: glyph name and its (first) code point.\n`;
  rust += `pub(crate) static ${rustName}: [(&str, u32); ${entries.length}] = [\n`;
  for (const [name, code] of entries) {
    rust += `    (${JSON.stringify(name)}, 0x${code.toString(16).toUpperCase().padStart(4, '0')}),\n`;
  }
  rust += '];\n';
  return entries.length;
};
const glyphs = glyphList(glyphlistPath, 'GLYPH_LIST', 'Adobe Glyph List');
rust += '\n';
const dingbats = glyphList(zapfPath, 'ZAPF_DINGBATS_LIST', 'ZapfDingbats glyph list');

// Widths of the Core 14 fonts Symbol and ZapfDingbats, by glyph name, in
// thousandths of text space, sorted by name.
const metrics = readFileSync(metricsPath, 'utf8');
for (const [rustName, jsName, doc] of [
  ['SYMBOL_WIDTHS', 't.Symbol', 'Symbol'],
  ['ZAPF_DINGBATS_WIDTHS', 't.ZapfDingbats', 'ZapfDingbats'],
]) {
  const start = metrics.indexOf(`${jsName} = getLookupTableFactory(function (t) {`);
  if (start < 0) throw new Error(`${jsName} not found`);
  const body = metrics.slice(start, metrics.indexOf('});', start));
  const widths = [...body.matchAll(/^\s*t(?:\.([A-Za-z0-9_]+)|\["([A-Za-z0-9._]+)"\]) = (\d+);$/gm)]
    .map(m => [m[1] ?? m[2], Number(m[3])]);
  if (widths.length < 100) throw new Error(`${jsName}: ${widths.length} widths`);
  widths.sort(byName);
  unique(widths, rustName);
  rust += `\n/// Widths of ${doc} (Adobe Core 14 AFM), sorted by glyph name.\n`;
  rust += `pub(crate) static ${rustName}: [(&str, u16); ${widths.length}] = [\n`;
  for (const [name, width] of widths) rust += `    (${JSON.stringify(name)}, ${width}),\n`;
  rust += '];\n';
}
writeFileSync(out, rust);
console.log(`${out}: ${tables.length} encodings, ${glyphs} glyph names, ${dingbats} dingbats`);
